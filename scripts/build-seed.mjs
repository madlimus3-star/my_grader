/**
 * Regenerate lib/seed-data.js from data/problems.
 *
 *   node scripts/build-seed.mjs
 *
 * The seed is only a fallback: serverless deployments normally read data/ from
 * the bundle (vercel.json includeFiles). Keeping the seed committed guarantees
 * a fresh deployment still shows the problems even if that glob changes.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const problemsDir = path.join(root, 'data', 'problems');
const outFile = path.join(root, 'lib', 'seed-data.js');

const readJson = async (file) => {
  try {
    return JSON.parse(await fs.readFile(file, 'utf8'));
  } catch {
    return null;
  }
};

const idRe = /^[a-z0-9][a-z0-9-]{0,63}$/;
const db = { version: 1, problems: {}, submissions: [] };

const entries = await fs.readdir(problemsDir, { withFileTypes: true }).catch(() => []);
for (const entry of entries) {
  if (!entry.isDirectory() || !idRe.test(entry.name)) continue;
  const dir = path.join(problemsDir, entry.name);
  const meta = await readJson(path.join(dir, 'problem.json'));
  if (!meta) continue;

  const index = (await readJson(path.join(dir, 'tests', 'index.json'))) || { tests: [] };
  const tests = [];
  for (const test of Array.isArray(index.tests) ? index.tests : []) {
    const input = await fs.readFile(path.join(dir, 'tests', `${test.id}.in`), 'utf8').catch(() => '');
    const expected = await fs.readFile(path.join(dir, 'tests', `${test.id}.out`), 'utf8').catch(() => '');
    tests.push({ ...test, input, expected });
  }

  let statement = null;
  if (meta.statementFile) {
    const buffer = await fs.readFile(path.join(dir, meta.statementFile)).catch(() => null);
    if (buffer) {
      statement = {
        name: meta.statementName || meta.statementFile,
        bytes: buffer.length,
        base64: buffer.toString('base64'),
      };
    }
  }

  db.problems[entry.name] = {
    meta: { ...meta, statementPages: 0 },
    statement,
    tests,
  };
}

const banner = '// Generated by scripts/build-seed.mjs — do not edit by hand.\n';
await fs.writeFile(outFile, `${banner}export const SEED = ${JSON.stringify(db)};\n`);
const size = (await fs.stat(outFile)).size;
console.log(`wrote ${path.relative(root, outFile)} (${(size / 1024).toFixed(1)} KB, ${Object.keys(db.problems).length} problems)`);
